/**
 * The northern half of California, and the towns used as distance references.
 *
 * The outline is real boundary data, not drawn from memory — a recognisable shape
 * approximated by hand is a factual error that readers spot immediately. Source:
 * public US state boundary GeoJSON (state boundaries are US government public
 * domain), clipped to latitude 37.27°N, which is the midpoint of California's
 * 32.53–42.01 span, then reduced with Douglas–Peucker at a tolerance no coarser
 * than the rendered map can show.
 *
 * CHANGES OFTEN: no. This is geography.
 * SIGNED OFF BY: build decision. The distances below are computed, not asserted —
 * see `haversineMiles` in src/lib/map.ts.
 */

